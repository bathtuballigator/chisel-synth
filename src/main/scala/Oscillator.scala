import chisel3._
import chisel3.util.log2Ceil
import chisel3.util.Fill

abstract class BaseOscillator(
    amp: Int,
    sampleWid: Int,
    phaseWid: Int
) extends Module {
  val io = IO(new Bundle {
    // chisel hardware unsigned
    val increment = Input(
      UInt(phaseWid.W)
    ) // increment value for the phase accumulator, calculated from frequency and sample rate
    // neeeds to be signed
    val sample = Output(SInt(sampleWid.W)) // output sample, signed
  })
    // require non-neg values
  require(
    amp >= 0,
    "Amplitude must not be negative"
  ) // I allowed zero amplitude, which will just output a constant 0
  require(sampleWid > 1, "Sample width must be >1") // number of bits
  require(phaseWid > 2, "Phase width must be >2") // number of bits (needs to be >2 for triangle wave, which uses MSB and next MSB for direction)
  require(
    amp < (1 << (sampleWid - 1)),
    "Amplitude must fit in signed sample width"
  ) // if sample width is 8 bits, max amplitude is 127, if sample width is 16 bits, max amplitude is 32767, etc.
}

class PWMOscillator(
    freq: Int = 440,
    clock_speed: Int = 100_000_000
) extends Module {
  val size: Int = clock_speed / freq
  val width: Int = log2Ceil(size)
  val PWM_in: UInt = (size >> 1).U

  val io = IO(new Bundle {
    val PWM_out = Output(Bool())
  })

  val acc = RegInit(0.U(width.W))
  val PWM_out_reg = RegInit(0.B)
  val PWM_thresh = RegInit((size >> 1).U(width.W))

  acc := Mux(acc === (size - 1).U, 0.U, acc + 1.U)
  PWM_thresh := Mux(acc === 0.U, PWM_in, PWM_thresh)
  PWM_out_reg := acc >= PWM_thresh
  io.PWM_out := PWM_out_reg

}

class SquareOscillator (
    amp: Int,
    sampleWid: Int,
    phaseWid: Int
) extends BaseOscillator(amp, sampleWid, phaseWid) { // class for an oscillator that uses an accumulator to generate a square wave

  // accumulator
  val acc = RegInit(0.U(phaseWid.W))
  // increment
  acc := acc + io.increment // overflow will wrap around

  // for square wave, just use MSB
  // if MSB is 1, output -amp
  // if MSB is 0, output +amp
  // that divides the phase in half
  io.sample := Mux(
    acc(phaseWid - 1),
    (-amp).S(sampleWid.W),
    (+amp).S(sampleWid.W)
  )
}

object OscConfig // calculate increment of the square wave oscillator for given frequency, sample rate, and phase width
{
  def calcIncrement(
      freq: Int, // frequency of the square wave
      sampleRate: Int, // sample rate of the DAC in Hz
      phaseWid: Int // number of bits in the phase accumulator
  ): BigInt = {
    require(
      freq >= 0,
      "Frequency must be non-negative"
    ) // allow zero frequency, which will just output a constant value
    require(
      freq < sampleRate / 2,
      "Frequency must be less than Nyquist frequency"
    ) // must be less than half the sample rate to avoid aliasing/acheive perfect fideltiy (Nyquist–Shannon sampling theorem)
    require(sampleRate > 0, "Sample rate must be positive") // Hz
    require(
      phaseWid > 0,
      "Phase width must be positive"
    ) // number of bits in phase accumulator
    // generated during elaboration phase, so mult/div are not on FPGA
    (BigInt(freq) * (BigInt(
      1
    ) << phaseWid)) / sampleRate // increment = freq * 2^phaseWid / sampleRate
  }
}


class SawOscillator (
    amp: Int,
    sampleWid: Int,
    phaseWid: Int
) extends BaseOscillator(amp, sampleWid, phaseWid) {
  // accumulator
  val acc = RegInit(0.U(phaseWid.W))
  // increment
  acc := acc + io.increment // overflow will wrap around

  // ramp is generated by taking all bits of acc except MSB
  // then mult by 2*amp and divide by 2^(phaseWid-1) to scale to desired amplitude8
  // then subtract amp to center around 0
  // accumulator gives linear ramp
  io.sample := (acc(phaseWid - 2, 0) * (2 * amp).S(sampleWid.W)) / ((1 << (phaseWid - 1)) - 1).S(sampleWid.W) - amp.S(sampleWid.W)
}

class TriangleOscillator (
    amp: Int,
    sampleWid: Int,
    phaseWid: Int
) extends BaseOscillator(amp, sampleWid, phaseWid) {

  // accumulator
  val acc = RegInit(0.U(phaseWid.W))
  // increment
  acc := acc + io.increment // overflow will wrap around

  // triangle wave is generated by taking all bits of acc except MSB
  // for linear output
  // XORing with MSB to flip direction for negative slope
  // then mult by 2*amp and divide by 2^(phaseWid-1) to scale to desired amplitude8
  // then subtract amp to center around 0
    io.sample := ((acc(phaseWid - 2, 0) ^ Fill(phaseWid - 1, acc(phaseWid - 1))) * (2 * amp).S(sampleWid.W)) / ((1 << (phaseWid - 1)) - 1).S(sampleWid.W) - amp.S(sampleWid.W)

}

class SineOscillator (
    amp: Int,
    sampleWid: Int,
    phaseWid: Int
) extends BaseOscillator(amp, sampleWid, phaseWid) {

  // sine wave needs lookup table, so need to create ROM with 2^phaseWid entries
  // each entry is sampleWid bits
  val sineTable = Mem(1 << phaseWid, SInt(sampleWid.W))
  // fill sineTable with values from -amp to +amp
  for (i <- 0 until (1 << phaseWid)) {
    sineTable(i) := (Math.sin(2 * Math.PI * i / (1 << phaseWid)) * amp).toInt.S(sampleWid.W)
  }
  // accumulator to index into sineTable
    val acc = RegInit(0.U(phaseWid.W))
    // increment
    acc := acc + io.increment // overflow will wrap around
    // output sample from sineTable
    io.sample := sineTable(acc)
}


// enumeration for oscillator types
object OscType extends ChiselEnum {
  val Sine, Square, Saw, Triangle = Value
}

// wrapper that picks type based on enum
class Oscillator(
    oscType: OscType.Type, // type of oscillator to generate
    amp: Int, // the amplitude of the wave
    sampleWid: Int, // the number of bits in the output sample
    phaseWid: Int // the number of bits in the phase accumulator
) extends Module {
  val io = IO(new Bundle {
    // chisel hardware unsigned
    val increment = Input(
      UInt(phaseWid.W)
    ) // increment value for the phase accumulator, calculated from frequency and sample rate
    // neeeds to be signed
    val sample = Output(SInt(sampleWid.W)) // output sample, signed
  })

  // instatiate correct osc type
    val osc: BaseOscillator = oscType match {
        case OscType.Sine     => Module(new SineOscillator(amp, sampleWid, phaseWid))
        case OscType.Square   => Module(new SquareOscillator(amp, sampleWid, phaseWid))
        case OscType.Saw      => Module(new SawOscillator(amp, sampleWid, phaseWid))
        case OscType.Triangle => Module(new TriangleOscillator(amp, sampleWid, phaseWid))
    }
    // connect in and outs
    osc.io.increment := io.increment
    io.sample := osc.io.sample
}

