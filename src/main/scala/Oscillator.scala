sealed trait OscillatorType
object OscillatorType {
  case object Sine extends OscillatorType
  case object Square extends OscillatorType
  case object Saw extends OscillatorType
  case object Triangle extends OscillatorType
}

abstract class BaseOscillator(
    amp: Int,
    sampleWid: Int,
    phaseWid: Int
) extends Module {
  val io = IO(new Bundle {
    // chisel hardware unsigned
    val increment = Input(
      UInt(phaseWid.W)
    ) // increment value for the phase accumulator, calculated from frequency and sample rate
    // neeeds to be signed
    val sample = Output(SInt(sampleWid.W)) // output sample, signed
  })
    // require non-neg values
  require(
    amp >= 0,
    "Amplitude must not be negative"
  ) // I allowed zero amplitude, which will just output a constant 0
  require(sampleWid > 1, "Sample width must be >1") // number of bits
  require(phaseWid > 2, "Phase width must be >2") // number of bits (needs to be >2 for triangle wave, which uses MSB and next MSB for direction)
  require(
    amp < (BigInt(1) << (sampleWid - 1)),
    "Amplitude must fit in signed sample width"
  ) // if sample width is 8 bits, max amplitude is 127, if sample width is 16 bits, max amplitude is 32767, etc.
}

class SquareOscillator (
    amp: Int,
    sampleWid: Int,
    phaseWid: Int
) extends BaseOscillator(amp, sampleWid, phaseWid) { // class for an oscillator that uses an accumulator to generate a square wave

  // accumulator
  val acc = RegInit(0.U(phaseWid.W))
  // increment
  acc := acc + io.increment // overflow will wrap around

  // for square wave, just use MSB
  // if MSB is 1, output -amp
  // if MSB is 0, output +amp
  // that divides the phase in half
  io.sample := Mux(
    acc(phaseWid - 1),
    (-amp).S(sampleWid.W),
    (+amp).S(sampleWid.W)
  )
}

object OscConfig // calculate increment of the square wave oscillator for given frequency, sample rate, and phase width
{
  def calcIncrementAndWidth(
      freq: Int, // frequency of the wave
      clockFrequency: Int, // in Hz
  ): (UInt, Int) = {
    require(clockFrequency > 0, "Sample rate must be positive") // Hz
    require(
      freq >= 0,
      "Frequency must be non-negative"
    ) // allow zero frequency, which will just output a constant value
    require(
      BigInt(freq) *2 < BigInt(clockFrequency),
      "Frequency must be less than Nyquist frequency"
    ) // must be less than half the sample rate to avoid aliasing/acheive perfect fideltiy (Nyquist–Shannon sampling theorem)

    // generated during elaboration phase, so mult/div are not on FPGA
    val size: Int = clockFrequency / freq
    ((size >> 1).U, log2Ceil(size))
  }
}


class SawOscillator (
    amp: Int,
    sampleWid: Int,
    phaseWid: Int
) extends BaseOscillator(amp, sampleWid, phaseWid) {
  // accumulator
  val acc = RegInit(0.U(phaseWid.W))
  // increment
  acc := acc + io.increment // overflow will wrap around

  // ramp is generated by taking all bits of acc except MSB
  // then mult by 2*amp and divide by 2^(phaseWid-1) to scale to desired amplitude8
  // then subtract amp to center around 0
  // accumulator gives linear ramp
  // io.sample := (acc(phaseWid - 2, 0) * (2 * amp).S(sampleWid.W)) / ((1 << (phaseWid - 1)) - 1).S(sampleWid.W) - amp.S(sampleWid.W)
  // exclude MSB for ramp values
  val ramp = acc(phaseWid - 2, 0)

  // make sure calculated width is enough to hold the intermediate values
  val calcWid = phaseWid + sampleWid + 2
  // pad ramp with zeros to calcWid
  val rampWide = ramp.pad(calcWid)
  // scale to 2*amp and divide by 2^(phaseWid-1) to scale to desired amp
  // sepated out for clarity
  val scale = (BigInt(2) * amp).U(calcWid.W)
  val denominator = ((BigInt(1) << (phaseWid - 1)) - 1)
    .U(calcWid.W)

  val scaled = (rampWide * scale) / denominator

  // subtract amp to center around 0
  // zero extend amp to calcWid to match scaled width
  val centered = scaled.zext - amp.S(calcWid.W)

  io.sample := centered(sampleWid - 1, 0).asSInt
}

class TriangleOscillator (
    amp: Int,
    sampleWid: Int,
    phaseWid: Int
) extends BaseOscillator(amp, sampleWid, phaseWid) {

  // accumulator
  val acc = RegInit(0.U(phaseWid.W))
  // increment
  acc := acc + io.increment // overflow will wrap around

  // triangle wave is generated by taking all bits of acc except MSB
  // for linear output
  // XORing with MSB to flip direction for negative slope
  // then mult by 2*amp and divide by 2^(phaseWid-1) to scale to desired amplitude8
  // then subtract amp to center around 0
    // io.sample := ((acc(phaseWid - 2, 0) ^ Fill(phaseWid - 1, acc(phaseWid - 1))) * (2 * amp).S(sampleWid.W)) / ((1 << (phaseWid - 1)) - 1).S(sampleWid.W) - amp.S(sampleWid.W)
  // exclude MSB for ramp values
  val ramp = acc(phaseWid - 2, 0)

  // make sure calculated width is enough to hold the intermediate values
  val calcWid = phaseWid + sampleWid + 2
  // XOR with MSB to flip direction for negative slope
  val flipped = ramp ^ Fill(phaseWid - 1, acc(phaseWid - 1))
  val flippedPad = flipped.pad(calcWid) // pad after flipping so the extra bits are not flipped
  // scale to 2*amp and divide by 2^(phaseWid-1) to scale to desired amp
  // separated out for clarity
  val scale = (BigInt(2) * amp).U(calcWid.W)
  val denominator = ((BigInt(1) << (phaseWid - 1)) - 1)
    .U(calcWid.W)

  val scaled = (flippedPad * scale) / denominator

  // subtract amp to center around 0
  // zero extend amp to calcWid to match scaled width
  val centered = scaled.zext - amp.S(calcWid.W)

  // explicitly set width of output to sampleWid, since it is a signed value
  // use asSInt to convert to signed
  io.sample := centered(sampleWid - 1, 0).asSInt

}

class SineOscillator (
    amp: Int,
    sampleWid: Int,
    phaseWid: Int
) extends BaseOscillator(amp, sampleWid, phaseWid) {

  // sine wave needs lookup table
  // needs to be generated at elaboration time
  // VecInit used instead
  // sine tavle is 2^tableAddrWid entries, each entry is sampleWid bits
  // TODO: look at making table smaller by using symmetry and only storing 1/4 of the wave, then mirroring and inverting as needed
  // each entry is sampleWid bits
    val tableAddrWid = math.min(phaseWid, 10) // separate from phaseWid, so that table can be smaller than phase accumulator
    // max out at 10bit = 1024 entries
    // otherwise deualt would be 2^16=65k
    // changed to math.min so it is decided during elaboration instead of in hardware
    require(phaseWid >= tableAddrWid)
    val sineTable = VecInit(
        (0 until (1 << tableAddrWid)).map { i =>
            (Math.sin(2.0 * Math.PI * i / (1 << tableAddrWid)) * amp)
              .toInt.S(sampleWid.W)
        }
    )
  // accumulator to index into sineTable
    val acc = RegInit(0.U(phaseWid.W))
    // increment
    acc := acc + io.increment // overflow will wrap around
    
    val idx = acc(phaseWid - 1, phaseWid - tableAddrWid) // use MSBs of acc to index, since table is smaller than phase accumulator, so use MSBs to index into table

    // output sample from sineTable
    io.sample := sineTable(idx)
}

// wrapper that picks type based on enum
class Oscillator(
    oscType: OscillatorType, // type of oscillator to generate
    amp: Int, // the amplitude of the wave
    sampleWid: Int, // the number of bits in the output sample
    phaseWid: Int // the number of bits in the phase accumulator
) extends Module {
  val io = IO(new Bundle {
    // chisel hardware unsigned
    val increment = Input(
      UInt(phaseWid.W)
    ) // increment value for the phase accumulator, calculated from frequency and sample rate
    // neeeds to be signed
    val sample = Output(SInt(sampleWid.W)) // output sample, signed
  })

  // instatiate correct osc type
    val osc: BaseOscillator = oscType match {
        case OscillatorType.Sine     => Module(new SineOscillator(amp, sampleWid, phaseWid))
        case OscillatorType.Square   => Module(new SquareOscillator(amp, sampleWid, phaseWid))
        case OscillatorType.Saw      => Module(new SawOscillator(amp, sampleWid, phaseWid))
        case OscillatorType.Triangle => Module(new TriangleOscillator(amp, sampleWid, phaseWid))
    }
    // connect in and outs
    osc.io.increment := io.increment
    io.sample := osc.io.sample
}




class PWMGenerator( // renamed to generator bc it uses the oscillator to generate a PWM signal
    freq: Int = 440,
    clock_speed: Int = 100_000_000,
    amp: Int = 127, // default to max for 8bit signed
    sampleWid: Int = 8, // default to 8 bit
    voice: OscillatorType = OscillatorType.Square // default to square wave
) extends Module {

  val io = IO(new Bundle {
    val PWM_en =Input(Bool())
    val PWM_out = Output(Bool())
  })

  // calc increment for osc
  val (increment,incrementWidth) = OscConfig.calcIncrementAndWidth(freq, clock_speed)

  // instantiate the oscillator
  val osc = Module(new Oscillator(voice, amp, sampleWid, incrementWidth))
  // connect io
  osc.io.increment := increment
  // convert signed sample to unsigned PWM threshold
  val sample = osc.io.sample
  val pwmThres =sample.asUInt ^ (BigInt(1) << (sampleWid - 1)).U(sampleWid.W) // convert signed to unsigned by adding 2^(sampleWid-1) to shift range from [-amp, amp] to [0, 2*amp]
  // XOR with sign bit (MSB) is equivalent but cheaper

  // carrier counter for PWM
  // does not depend on frequency
  val pwmCounter = RegInit(0.U(sampleWid.W))
  pwmCounter := pwmCounter + 1.U

  // NOTE AFTER CHANGING calcIncrement: Idk what this means or if still true
  // yields carrier frequency of clock_speed / 2^sampleWid
  // default is 100MHz / 256 = 391kHz

  // mux to enable/disable PWM output
  // output value 
  io.PWM_out := io.PWM_en && (pwmCounter < pwmThres) // only outputs when PWM_en is high, otherwise output 0
}
